// Command version-compat-gen renders pkg/version/zz_generated.compatibility.go
// from versions.yml. The compatibility rule has to know the last minor release
// of each superseded major line, and that fact only lives in versions.yml, so
// deriving it keeps the two in step instead of hand-editing a map at every
// major bump. Run through `make generate/versions`.
package main

import (
	"fmt"
	"os"
	"slices"
	"strings"

	"github.com/Masterminds/semver/v3"
	"sigs.k8s.io/yaml"
)

const versionsFile = "versions.yml"

type release struct {
	Version string `json:"version"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "version-compat-gen:", err)
		os.Exit(1)
	}
}

func run() error {
	content, err := os.ReadFile(versionsFile)
	if err != nil {
		return err
	}

	var releases []release
	if err := yaml.Unmarshal(content, &releases); err != nil {
		return err
	}

	lastMinor := map[uint64]uint64{}
	for _, entry := range releases {
		version, err := semver.NewVersion(entry.Version)
		if err != nil {
			// versions.yml names the unreleased line "preview", which is not semver. // EXC:FILE011:documents-the-preview-row
			continue
		}
		if version.Minor() > lastMinor[version.Major()] {
			lastMinor[version.Major()] = version.Minor()
		}
	}

	majors := make([]uint64, 0, len(lastMinor))
	for major := range lastMinor {
		majors = append(majors, major)
	}
	slices.Sort(majors)

	var out strings.Builder
	out.WriteString("// Code generated by tools/ci/version-compat-gen. DO NOT EDIT.\n\n")
	out.WriteString("package version\n\n")
	out.WriteString("// lastMinorOfMajor records the final minor release of every major line in\n")
	out.WriteString("// versions.yml. It is generated from that file, so it cannot go stale:\n")
	out.WriteString("// `make check` fails when this file is out of date.\n")
	out.WriteString("var lastMinorOfMajor = map[uint64]uint64{\n")
	for _, major := range majors {
		fmt.Fprintf(&out, "\t%d: %d,\n", major, lastMinor[major])
	}
	out.WriteString("}\n")

	_, err = os.Stdout.WriteString(out.String())
	return err
}
