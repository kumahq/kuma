package v1alpha1_test

import (
	"bytes"
	"testing"

	v1 "k8s.io/apimachinery/pkg/apis/meta/v1"

	common_api "github.com/kumahq/kuma/v2/api/common/v1alpha1"
	meshidentity_api "github.com/kumahq/kuma/v2/pkg/core/resources/apis/meshidentity/api/v1alpha1"
	"github.com/kumahq/kuma/v2/pkg/test/resources/builders"
	test_model "github.com/kumahq/kuma/v2/pkg/test/resources/model"
)

func meshIdentityWithStatus(version string, condition common_api.Condition) *meshidentity_api.MeshIdentityResource {
	identity := builders.MeshIdentity().
		WithMesh("default").
		WithName("identity-1").
		WithBundledAutoGenerated().
		Build()
	identity.Meta.(*test_model.ResourceMeta).Version = version
	identity.Status = &meshidentity_api.MeshIdentityStatus{Conditions: []common_api.Condition{condition}}
	return identity
}

func TestMeshIdentityXDSHashIgnoresVersionAndStatusDetails(t *testing.T) {
	first := meshIdentityWithStatus("1", common_api.Condition{
		Type:   meshidentity_api.ReadyConditionType,
		Status: v1.ConditionTrue,
		Reason: "Ready",
	})
	second := meshIdentityWithStatus("2", common_api.Condition{
		Type:    meshidentity_api.ReadyConditionType,
		Status:  v1.ConditionTrue,
		Reason:  "Rotated",
		Message: "CA rotated",
	})

	if !bytes.Equal(first.XDSHash(), second.XDSHash()) {
		t.Fatal("expected MeshIdentity XDSHash to ignore version and status details")
	}
	if bytes.Equal(first.Hash(), second.Hash()) {
		t.Fatal("expected MeshIdentity Hash to change when version/status changes")
	}
}

// A zone egress is advertised to the whole mesh only once its MeshIdentity is initialized, so
// the readiness flip has to invalidate mesh-wide xDS even though nothing else changed.
func TestMeshIdentityXDSHashTracksInitialization(t *testing.T) {
	ready := meshIdentityWithStatus("1", common_api.Condition{
		Type:   meshidentity_api.ReadyConditionType,
		Status: v1.ConditionTrue,
		Reason: "Ready",
	})
	notReady := meshIdentityWithStatus("1", common_api.Condition{
		Type:   meshidentity_api.ReadyConditionType,
		Status: v1.ConditionFalse,
		Reason: "PartiallyReady",
	})

	if bytes.Equal(ready.XDSHash(), notReady.XDSHash()) {
		t.Fatal("expected MeshIdentity XDSHash to change when the Ready condition flips")
	}
}
