package v1alpha1_test

import (
	"bytes"
	"testing"

	v1 "k8s.io/apimachinery/pkg/apis/meta/v1"

	common_api "github.com/kumahq/kuma/v2/api/common/v1alpha1"
	meshidentity_api "github.com/kumahq/kuma/v2/pkg/core/resources/apis/meshidentity/api/v1alpha1"
	"github.com/kumahq/kuma/v2/pkg/test/resources/builders"
	test_model "github.com/kumahq/kuma/v2/pkg/test/resources/model"
)

func identityWithStatus(version string, status *meshidentity_api.MeshIdentityStatus) *meshidentity_api.MeshIdentityResource {
	identity := builders.MeshIdentity().
		WithMesh("default").
		WithName("identity-1").
		WithBundledAutoGenerated().
		Build()
	identity.Meta.(*test_model.ResourceMeta).Version = version
	identity.Status = status
	return identity
}

func readyStatus(status v1.ConditionStatus, reason string) *meshidentity_api.MeshIdentityStatus {
	return &meshidentity_api.MeshIdentityStatus{
		Conditions: []common_api.Condition{{
			Type:   meshidentity_api.ReadyConditionType,
			Status: status,
			Reason: reason,
		}},
	}
}

func TestMeshIdentityXDSHashIgnoresVersionAndNonReadinessStatus(t *testing.T) {
	first := identityWithStatus("1", readyStatus(v1.ConditionFalse, "PartiallyReady"))
	second := identityWithStatus("2", readyStatus(v1.ConditionFalse, "NotReady"))

	if !bytes.Equal(first.XDSHash(), second.XDSHash()) {
		t.Fatal("expected MeshIdentity XDSHash to ignore version and non-readiness status conditions")
	}
	if bytes.Equal(first.Hash(), second.Hash()) {
		t.Fatal("expected MeshIdentity Hash to change when version/status changes")
	}
}

// Workload identity is only issued once the MeshIdentity is initialized, so the
// readiness flip has to invalidate the mesh context.
func TestMeshIdentityXDSHashTracksReadiness(t *testing.T) {
	notReady := identityWithStatus("1", readyStatus(v1.ConditionFalse, "PartiallyReady"))
	ready := identityWithStatus("1", readyStatus(v1.ConditionTrue, "Ready"))

	if bytes.Equal(notReady.XDSHash(), ready.XDSHash()) {
		t.Fatal("expected MeshIdentity XDSHash to change when readiness flips")
	}

	noStatus := identityWithStatus("1", nil)
	if !bytes.Equal(noStatus.XDSHash(), notReady.XDSHash()) {
		t.Fatal("expected MeshIdentity XDSHash to treat a missing status as not ready")
	}
}
